#!/usr/bin/env python3
"""C33: download decks + OPM Flow reference summaries from OPM/opm-tests and write a regression manifest for
`ResSimCLI --regress`.

    python fetch_opm_tests.py [-o opm-tests] [--dirs spe1,spe3,spe9,...] [--all] [--max-mb 20] [--update]

Only the deck folders (deck + INCLUDE files, without the reference / ECLIPSE result folders) and the reference
SMSPEC + UNSMRY of each deck are downloaded (an opm-tests clone is several GB). A case is every top-level *.DATA of a
folder that has <folder>/opm-simulation-reference/flow/<NAME>.SMSPEC. Re-running only fetches missing files
(--update re-fetches the tree listing and changed sizes). Standard library only.
"""
import argparse
import json
import os
import sys
import urllib.request

REPO = "OPM/opm-tests"
RAW = "https://raw.githubusercontent.com/" + REPO + "/master/"
TREE = "https://api.github.com/repos/" + REPO + "/git/trees/master?recursive=1"
# black-oil decks that the ResSim engine is meant to run (folders of opm-tests); --all takes every folder
DEFAULT_DIRS = [
    "spe1", "spe3", "spe5", "spe9", "spe9group", "aquifer-fetkovich", "aquifer-num", "aquifer-oilwater", "actionx", "udq_actionx",
    "wsegsicd", "wsegaicd", "wsegvalv", "msw", "msw_2d_h", "polymer_simple2D", "spe1_brine", "gconprod", "gconinje", "wecon_wtest",
    "wtest", "vfpprod_spe1", "network", "model2", "krnum", "jfunc", "swatinit", "tracer", "pinch", "minpv", "editnnc", "mult",
    "rock", "three_phase_relperm", "wpimult", "welspecs", "gaslift", "co2store", "spe1_solvent", "spe1_foam",
]
SKIP_PARTS = ("opm-simulation-reference", "eclipse-simulation", "eclipse-reference", "restart_eclipse", "flow_diagnostic")


def get(url, path=None):
    req = urllib.request.Request(url, headers={"User-Agent": "ResSim-regression/1.0"})
    with urllib.request.urlopen(req, timeout=120) as r:
        data = r.read()
    if path:
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
    return data


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--out", default="opm-tests")
    ap.add_argument("--dirs", default="")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--max-mb", type=float, default=20.0, help="largest single file downloaded")
    ap.add_argument("--update", action="store_true")
    ap.add_argument("--tol", type=float, default=0.05)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    tree_file = os.path.join(a.out, "tree.json")
    if a.update or not os.path.exists(tree_file):
        print("listing", REPO, "...")
        get(TREE, tree_file)
    tree = json.load(open(tree_file))
    files = {e["path"]: e.get("size", 0) for e in tree["tree"] if e["type"] == "blob"}
    dirs = [d for d in a.dirs.split(",") if d] if a.dirs else None
    if a.all:
        dirs = sorted({p.split("/")[0] for p in files if "/" in p})
    dirs = dirs or DEFAULT_DIRS
    cases = []
    for d in dirs:
        decks = [p for p in files if p.startswith(d + "/") and p.count("/") == 1 and p.upper().endswith(".DATA")]
        for deck in sorted(decks):
            name = os.path.splitext(os.path.basename(deck))[0]
            ref = f"{d}/opm-simulation-reference/flow/{name}.SMSPEC"
            uns = f"{d}/opm-simulation-reference/flow/{name}.UNSMRY"
            if ref in files and uns in files:
                cases.append((d, name, deck, ref, uns))
    print(len(cases), "cases with OPM Flow references in", len(dirs), "folders")
    need = set()
    for d, name, deck, ref, uns in cases:
        need.update([ref, uns])
        for p, size in files.items():
            if p.startswith(d + "/") and not any(s in p.split("/") for s in SKIP_PARTS) and size <= a.max_mb * 1e6:
                ext = os.path.splitext(p)[1].upper()
                if ext in (".UNRST", ".EGRID", ".INIT", ".UNSMRY", ".SMSPEC", ".RFT", ".PRT", ".H5", ".PNG", ".PDF"):
                    continue
                need.add(p)
    total = 0
    for i, p in enumerate(sorted(need)):
        dst = os.path.join(a.out, p)
        if os.path.exists(dst) and os.path.getsize(dst) == files[p]:
            continue
        try:
            get(RAW + urllib.request.quote(p), dst)
            total += files[p]
            print(f"[{i + 1}/{len(need)}] {p}")
        except Exception as e:
            print("  failed", p, e, file=sys.stderr)
    man = os.path.join(a.out, "manifest.txt")
    with open(man, "w") as f:
        f.write("# ResSim deck regression manifest (generated by fetch_opm_tests.py from OPM/opm-tests)\n")
        f.write(f"tol {a.tol}\n")
        f.write("keys FOPR,FOPT,FWPR,FWPT,FGPR,FGPT,FWIR,FWIT,FGIR,FGIT,FPR,FWCT,FGOR,WBHP:*,WOPR:*,WWPR:*,WGPR:*\n")
        for d, name, deck, ref, uns in cases:
            f.write(f"case {name} deck={deck} ref={ref} group={d}\n")
    print(f"downloaded {total / 1e6:.1f} MB; wrote {man} ({len(cases)} cases)")
    print("run:  ResSimCLI --regress", man, "-o regression_out")


if __name__ == "__main__":
    main()
