#!/usr/bin/env python3
"""Generate ResSim's ECLIPSE keyword tables from OPM metadata.

Inputs (clone them first):
  opm-common/opm/input/eclipse/share/keywords/**          keyword record structure (JSON)
  opm-flow-editor-support/vscode-extension/data/keyword_index_compact.json   documentation index

Outputs:
  engine/src/keyword_db.inc      compiled-in record structure of every keyword (names, sections, size rules)
  app/res/keyword_docs.txt       documentation loaded at run time by the deck viewer / keyword reference

usage: python3 tools/gen_keywords.py OPM_COMMON_KEYWORD_DIR EDITOR_INDEX_JSON
The keyword metadata comes from the Open Porous Media project (https://opm-project.org), GPL-3.0.
"""
import json, os, re, sys

kwdir, idxfile = sys.argv[1], sys.argv[2]
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)

SECTIONS = ["RUNSPEC", "GRID", "EDIT", "PROPS", "REGIONS", "SOLUTION", "SUMMARY", "SCHEDULE"]

def loose_json(text):
    try:
        return json.loads(text)
    except Exception:
        t = re.sub(r'"comment"\s*:\s*"(?:[^"\\]|\\.)*?"\s*,?', "", text, flags=re.S)
        t = re.sub(r"(?<=[\d])\.e", ".0e", t)
        t = re.sub(r",\s*([}\]])", r"\1", t)
        try:
            return json.loads(t)
        except Exception:
            return None

specs = {}
order = ["000_Eclipse100", "001_Eclipse300", "002_Frontsim", "900_OPM"]
for sub in order:
    d = os.path.join(kwdir, sub)
    if not os.path.isdir(d):
        continue
    for r, _, fs in os.walk(d):
        for f in sorted(fs):
            j = loose_json(open(os.path.join(r, f), encoding="utf-8", errors="replace").read())
            if not j or "name" not in j:
                continue
            j["_origin"] = sub
            if j["name"] not in specs:          # E100 definition wins over E300/OPM duplicates
                specs[j["name"]] = j

def item_index(kw, item):
    s = specs.get(kw)
    if not s:
        return None, None
    items = s.get("items") or (s.get("records") or [[]])[0]
    for n, it in enumerate(items):
        if it.get("name") == item:
            return n, it.get("default")
    return None, None

rows = []
regex_rows = []
for name, s in sorted(specs.items()):
    secs = s.get("sections") or []
    mask = 0
    for x in secs:
        if x in SECTIONS:
            mask |= 1 << SECTIONS.index(x)
    kind, n, rkw, ritem, rdef, shift, end = "Slash", 0, "", -1, 0, 0, ""
    size = s.get("size")
    if "code" in s:
        kind, end = "Code", s["code"].get("end", "")
    elif name in ("ACTIONX", "ACTIONW", "ACTIONG", "ACTIONR", "ACTIONS"):
        kind, end = "Action", "ENDACTIO"
    elif name == "PYACTION":
        kind, n = "Fixed", 2
    elif name == "TITLE":
        kind = "Raw"
    elif "num_tables" in s:
        kind = "Tables"
        rkw = s["num_tables"]["keyword"]
        ritem, rdef = item_index(rkw, s["num_tables"]["item"])
    elif "data" in s:
        kind, n = "Data", 1
    elif isinstance(size, int):
        kind, n = ("None", 0) if size == 0 else ("Fixed", size)
    elif isinstance(size, dict):
        kind = "FromKw"
        rkw = size["keyword"]
        ritem, rdef = item_index(rkw, size["item"])
        shift = int(size.get("shift", 0))
    elif size == "SPECIAL_CASE_ROCK":          # NTPVT records unless ROCKOPTS says otherwise (handled in C++)
        kind, rkw, ritem, rdef = "FromKw", "TABDIMS", 1, 1
    elif size == "UNKNOWN":
        kind = "Unknown"
    elif "items" in s or "records" in s or "alternating_records" in s or "records_set" in s:
        kind = "Slash"          # multi-record keywords (WELSEGS, COMPSEGS, ...): header record(s), then a '/'-closed list
    else:
        kind = "None"
    if kind == "FromKw" and ritem is None:
        kind, n = "Fixed", 1
    if kind == "Tables" and ritem is None:
        kind = "Slash"
    if rdef is None or isinstance(rdef, str):
        rdef = 1
    names = [name]
    if "deck_names" in s:
        names = [name] + list(s["deck_names"])
    if "deck_name" in s:            # alternative spelling accepted in decks (RPTRST / OUTSOL)
        names = [name] + (s["deck_name"] if isinstance(s["deck_name"], list) else [s["deck_name"]])
    names = [x for x in names if isinstance(x, str)]
    for dn in names:
        rows.append((dn, mask, kind, n, rkw, -1 if ritem is None else ritem, int(rdef), shift, end))
    if "deck_name_regex" in s:
        regex_rows.append((s["deck_name_regex"], mask, kind))

rows.sort()
seen = set()
out = []
out.append("// Generated by tools/gen_keywords.py from OPM keyword metadata (opm-common, GPL-3.0). Do not edit.\n")
out.append("// name, section mask (RUNSPEC GRID EDIT PROPS REGIONS SOLUTION SUMMARY SCHEDULE), size kind, fixed count,\n")
out.append("// size keyword, size item (0-based), size default, shift, end marker\n")
for r in rows:
    if r[0] in seen:
        continue
    seen.add(r[0])
    out.append('{"%s", %d, KwSize::%s, %d, "%s", %d, %d, %d, "%s"},\n' % r)
open(os.path.join(root, "engine/src/keyword_db.inc"), "w").write("".join(out))
rx = ["// Generated: summary-style keyword families matched by regular expression\n"]
for p, m, k in regex_rows:
    rx.append('{R"(%s)", %d, KwSize::%s},\n' % (p, m, k))
open(os.path.join(root, "engine/src/keyword_regex.inc"), "w").write("".join(rx))
print("structure:", len(seen), "keywords,", len(regex_rows), "regex families")

# ---------------------------------------------------------------- documentation
sys.path.insert(0, here)
import gen_docs
gen_docs.main(idxfile, os.path.join(root, "app/res/keyword_docs.txt"))
