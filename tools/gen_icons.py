#!/usr/bin/env python3
"""Generate the embedded UI icon font (subset of Lucide, ISC licence, https://lucide.dev).
   pip install fonttools ; python3 tools/gen_icons.py
Downloads lucide-static, keeps only the glyphs listed below and writes
   app/res/icons.ttf   (embedded as an RCDATA resource)
   app/src/icons.h     (ICON_* UTF-8 string macros + codepoint range for the font atlas)"""
import os, re, sys, urllib.request
from fontTools import subset
VER = "0.454.0"
ICONS = """play pause square circle-play circle-stop folder-open folder folder-tree save file file-plus file-code file-text
undo-2 redo-2 settings box cuboid layers grid-3x3 chart-line chart-spline chart-scatter chart-column chart-no-axes-combined
flask-conical target sliders-horizontal git-compare code eye eye-off filter crosshair camera download upload rotate-ccw
refresh-cw zoom-in maximize scan-line droplet droplets flame wrench hammer search text-search x check circle-alert
triangle-alert info list list-tree list-checks table square-stack layout-dashboard cpu gauge waves arrow-down-to-line
chevrons-down-up chevrons-up-down fold-vertical unfold-vertical copy scissors clipboard-paste message-square-code
book-open sparkles wand-sparkles route mouse-pointer-click trophy medal star history sigma shuffle split move-3d rotate-3d
axis-3d image activity trending-up server terminal pencil trash-2 plus minus circle-dot locate-fixed focus pin palette
sun moon scale mountain orbit network house log-out panel-left panel-right panel-bottom keyboard ellipsis brackets""".split()
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
base = f"https://cdn.jsdelivr.net/npm/lucide-static@{VER}/font/"
css = urllib.request.urlopen(base + "lucide.css").read().decode()
ttf = os.path.join("/tmp", "lucide_full.ttf")
open(ttf, "wb").write(urllib.request.urlopen(base + "lucide.ttf").read())
cps = {}
for n in ICONS:
    m = re.search(r"\.icon-" + re.escape(n) + r":before\s*\{\s*content:\s*\"\\([0-9a-f]+)\"", css)
    if not m:
        m2 = re.search(r"\.icon-" + re.escape(n) + r":before\s*\{[^}]*?\\([0-9a-f]+)", css)
        if not m2: sys.exit("icon not found: " + n)
        m = m2
    cps[n] = int(m.group(1), 16)
out_ttf = os.path.join(root, "app/res/icons.ttf")
opts = subset.Options(); opts.drop_tables += ["GSUB", "GPOS"]; opts.layout_features = []; opts.notdef_outline = True
f = subset.load_font(ttf, opts); s = subset.Subsetter(opts); s.populate(unicodes=list(cps.values())); s.subset(f)
subset.save_font(f, out_ttf, opts)
lo, hi = min(cps.values()), max(cps.values())
with open(os.path.join(root, "app/src/icons.h"), "w") as h:
    h.write("// Generated by tools/gen_icons.py - Lucide icons (ISC licence, https://lucide.dev), subset embedded as RCDATA.\n")
    h.write("#pragma once\n")
    h.write(f"#define ICON_MIN 0x{lo:04x}\n#define ICON_MAX 0x{hi:04x}\n")
    for n in ICONS:
        cp = cps[n]; b = chr(cp).encode("utf-8")
        h.write("#define ICON_%s \"%s\"\n" % (n.upper().replace("-", "_"), "".join("\\x%02x" % c for c in b)))
print(len(cps), "icons,", os.path.getsize(out_ttf), "bytes")
